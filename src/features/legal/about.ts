/** 본문의 ${...} 자리를 LEGAL_INFO 값으로 채운다. */
export function aboutText(): string {
  return ABOUT_TEXT.replace(/\$\{(\w+)\}/g, (match, key: string) =>
    key in LEGAL_INFO ? LEGAL_INFO[key as keyof typeof LEGAL_INFO] : match,
  )
}
